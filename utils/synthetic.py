"""SYNTHETIC placeholder data for tests and pipeline smoke runs.

Creates folder trees that mimic the *layout* of the four real sources, filled with
generated images (random low-frequency fields + a weak class-dependent band). These
images are not radiographs; results obtained on them say nothing about real
performance. Every generated tree contains a ``SYNTHETIC_DATA_README.txt`` marker.
"""
from __future__ import annotations

from pathlib import Path
from typing import Dict

import cv2
import numpy as np

CLASS_BAND = {"COVID-19": 0.2, "Pneumonia": 0.4, "Tuberculosis": 0.6, "Normal": 0.8}
MARKER = "SYNTHETIC_DATA_README.txt"


def synthetic_xray(label: str, rng: np.random.Generator, size: int = 256) -> np.ndarray:
    """One synthetic grayscale uint8 image. Weak class signal: a bright horizontal band."""
    low = rng.normal(0, 1, (6, 6)).astype(np.float32)
    field = cv2.resize(low, (size, size), interpolation=cv2.INTER_CUBIC)
    img = 120 + 45 * field + rng.normal(0, 8, (size, size))
    y = int(CLASS_BAND[label] * size)
    img[max(0, y - size // 20): y + size // 20, :] += 35
    return np.clip(img, 0, 255).astype(np.uint8)


def _write(path: Path, img: np.ndarray) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    ok, enc = cv2.imencode(path.suffix, img)
    assert ok, f"encode failed for {path}"
    enc.tofile(str(path))
    return path


def make_synthetic_sources(raw_dir: Path, n_per_class: int = 6, seed: int = 0, size: int = 256,
                           with_edge_cases: bool = True) -> Dict[str, Path]:
    """Create synthetic source trees under ``raw_dir``.

    Edge cases (``with_edge_cases``): one exact duplicate, one near duplicate (small
    brightness change), one corrupt file, one explicitly excluded label (Lung_Opacity),
    one unmapped folder, mask folders that must be skipped, and Kaggle patients with
    several images.
    """
    raw_dir = Path(raw_dir)
    rng = np.random.default_rng(seed)
    roots = {
        "covid_radiography": raw_dir / "COVID-19_Radiography_Dataset",
        "kaggle_pneumonia": raw_dir / "chest_xray",
        "montgomery_tb": raw_dir / "MontgomerySet",
        "shenzhen_tb": raw_dir / "ChinaSet_AllFiles",
    }
    for r in roots.values():
        r.mkdir(parents=True, exist_ok=True)
        (r / MARKER).write_text("SYNTHETIC test data generated by utils/synthetic.py. Not real radiographs.\n",
                                encoding="utf-8")
    cov = roots["covid_radiography"]
    for folder, label in [("COVID", "COVID-19"), ("Normal", "Normal"), ("Viral Pneumonia", "Pneumonia")]:
        for i in range(n_per_class):
            _write(cov / folder / "images" / f"{folder}-{i + 1}.png", synthetic_xray(label, rng, size))
    kag = roots["kaggle_pneumonia"]
    for i in range(n_per_class):
        split = ["train", "val", "test"][i % 3]
        _write(kag / split / "NORMAL" / f"IM-{i + 1:04d}-0001.jpeg", synthetic_xray("Normal", rng, size))
        kind = "bacteria" if i % 2 == 0 else "virus"
        _write(kag / split / "PNEUMONIA" / f"person{i + 1}_{kind}_{i + 1}.jpeg", synthetic_xray("Pneumonia", rng, size))
    mont = roots["montgomery_tb"] / "CXR_png"
    shen = roots["shenzhen_tb"] / "CXR_png"
    for i in range(n_per_class):
        _write(mont / f"MCUCXR_{i + 1:04d}_{i % 2}.png",
               synthetic_xray("Tuberculosis" if i % 2 else "Normal", rng, size))
        _write(shen / f"CHNCXR_{i + 1:04d}_{(i + 1) % 2}.png",
               synthetic_xray("Tuberculosis" if (i + 1) % 2 else "Normal", rng, size))

    if with_edge_cases:
        # exact duplicate (byte-identical copy) inside the COVID source
        src = cov / "COVID" / "images" / "COVID-1.png"
        (cov / "COVID" / "images" / "COVID-dup.png").write_bytes(src.read_bytes())
        # near duplicate: tiny brightness change of Normal-1
        n1 = cv2.imdecode(np.fromfile(str(cov / "Normal" / "images" / "Normal-1.png"), np.uint8), cv2.IMREAD_GRAYSCALE)
        _write(cov / "Normal" / "images" / "Normal-near.png", np.clip(n1.astype(int) + 3, 0, 255).astype(np.uint8))
        # corrupt file
        (cov / "COVID" / "images" / "COVID-corrupt.png").write_bytes(b"not a png at all")
        # explicitly excluded label + unmapped folder + mask folders (skipped)
        _write(cov / "Lung_Opacity" / "images" / "Lung_Opacity-1.png", synthetic_xray("Pneumonia", rng, size))
        _write(cov / "Other" / "images" / "Other-1.png", synthetic_xray("Normal", rng, size))
        _write(cov / "COVID" / "masks" / "COVID-1.png", np.zeros((size, size), np.uint8))
        _write(roots["montgomery_tb"] / "ManualMask" / "leftMask" / "MCUCXR_0001_0.png", np.zeros((size, size), np.uint8))
        # second image of an existing Kaggle patient (same patient id -> same group)
        _write(kag / "train" / "PNEUMONIA" / "person1_bacteria_99.jpeg", synthetic_xray("Pneumonia", rng, size))
    return roots


def synthetic_config(cfg: Dict, workdir: Path, n_per_class: int = 6, seed: int = 0, size: int = 256) -> Dict:
    """Deep copy of ``cfg`` whose data/output paths all live under ``workdir`` (absolute),
    with synthetic sources generated in ``workdir/data/raw``."""
    import copy

    workdir = Path(workdir).resolve()
    c = copy.deepcopy(cfg)
    for key, rel in {"raw_dir": "data/raw", "processed_dir": "data/processed", "manifest_dir": "data/manifests",
                     "manifest": "data/manifests/manifest.csv", "splits": "data/manifests/splits.json",
                     "data_report": "data/manifests/data_report.json", "outputs_dir": "outputs",
                     "checkpoints_dir": "checkpoints"}.items():
        c["paths"][key] = str(workdir / rel)
    roots = make_synthetic_sources(workdir / "data" / "raw", n_per_class=n_per_class, seed=seed, size=size)
    for name, root in roots.items():
        c["sources"][name]["root"] = str(root)
    c["_project_root"] = str(workdir)
    return c


def is_synthetic(cfg: Dict) -> bool:
    """True if any configured source root carries the synthetic-data marker."""
    from utils.config import resolve_path

    return any((resolve_path(cfg, src["root"]) / MARKER).is_file() for src in cfg["sources"].values())


def data_tag(cfg: Dict) -> str:
    """Title tag for plots/reports: '[SYNTHETIC DATA]' for synthetic workspaces, else ''."""
    return "[SYNTHETIC DATA]" if is_synthetic(cfg) else ""


def write_workspace(out_dir: Path, base_config: Path, n_per_class: int = 10, seed: int = 0,
                    overrides: Dict | None = None) -> Path:
    """Create a self-contained SYNTHETIC workspace (data + config.yaml) and return the config path."""
    import yaml

    from utils.config import load_config, public_config, set_by_path, validate_config

    cfg = synthetic_config(load_config(base_config), out_dir, n_per_class=n_per_class, seed=seed)
    cfg["experiment"]["name"] = cfg["experiment"]["model"]
    for k, v in (overrides or {}).items():
        set_by_path(cfg, k, v)
    validate_config(cfg)
    path = Path(out_dir).resolve() / "config.yaml"
    with path.open("w", encoding="utf-8") as fh:
        fh.write("# SYNTHETIC smoke-test workspace generated by utils/synthetic.py -- not real data.\n")
        yaml.safe_dump(public_config(cfg), fh, sort_keys=False)
    return path


def main(argv=None) -> int:
    import argparse

    ap = argparse.ArgumentParser(description="Create a SYNTHETIC smoke-test workspace")
    ap.add_argument("--out", required=True, help="workspace directory (created)")
    ap.add_argument("--config", default="configs/config.yaml", help="base config to copy settings from")
    ap.add_argument("--n-per-class", type=int, default=10)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--set", nargs="*", default=[], metavar="KEY=YAML",
                    help="config overrides, e.g. training.epochs=1 model.pretrained=false")
    args = ap.parse_args(argv)
    import yaml

    overrides = {kv.split("=", 1)[0]: yaml.safe_load(kv.split("=", 1)[1]) for kv in args.set}
    path = write_workspace(Path(args.out), Path(args.config), args.n_per_class, args.seed, overrides)
    print(f"SYNTHETIC workspace config: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
